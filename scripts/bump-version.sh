#!/usr/bin/env bash
#
# One version, bumped in one place. package.json is the source: flake.nix reads
# it, and this script copies it to the files that must hold a literal
# (src-tauri/Cargo.toml, Cargo.lock's entry for the app, tauri.conf.json, which
# release.yaml compares to the tag).
#
# Usage: scripts/bump-version.sh X.Y.Z   set the version everywhere
#        scripts/bump-version.sh --check fail when any copy differs from package.json
# Refuses a version not above both package.json's and the last tag, and one
# while another tracked file declares the outgoing version.
# Exit:  0 done or consistent · 1 copies differ · 2 bad usage, input or guard

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
pkg=package.json conf=src-tauri/tauri.conf.json toml=src-tauri/Cargo.toml lock=src-tauri/Cargo.lock

name="$(sed -n 's/^name = "\(.*\)"/\1/p' "$toml" | head -1)"
toml_version() { sed -n 's/^version = "\(.*\)"/\1/p' "$toml" | head -1; }
lock_version() {
  [ -f "$lock" ] || return 0
  awk -v n="$name" '$0 == "name = \"" n "\"" { getline; if ($1 == "version") { gsub(/"/, "", $3); print $3; exit } }' "$lock"
}

# True when $1 is strictly greater than $2, comparing major.minor.patch
# numerically (10# stops a zero-padded part reading as octal).
version_gt() {
  local -a a b; local i
  IFS=. read -r -a a <<<"${1%%-*}"; IFS=. read -r -a b <<<"${2%%-*}"
  for i in 0 1 2; do
    ((10#${a[i]} > 10#${b[i]})) && return 0
    ((10#${a[i]} < 10#${b[i]})) && return 1
  done
  return 1
}

# Files this script rewrites, and files that may state the outgoing version
# without being rewritten: the changelog records every version, lockfiles are
# regenerated by their own tooling.
rewritten=("$pkg" "$conf" "$toml" "$lock")
exempt=(CHANGELOG.md pnpm-lock.yaml package-lock.json yarn.lock)

# Guard 1: the version moves forwards past the in-tree version (what a source
# build reports) and the last tag (what consumers resolve). A tag-only check
# accepts a reset of untagged commits to an older number.
guard_forwards() {
  local current last
  current="$(jq -r .version "$pkg")"
  version_gt "$1" "$current" || { echo "$1 is not greater than the in-tree version $current; versions move forwards." >&2; exit 2; }
  last="$(git describe --tags --abbrev=0 2>/dev/null || true)"
  [ -z "$last" ] || version_gt "$1" "${last#v}" || { echo "$1 is not greater than the last tag $last." >&2; exit 2; }
}

# Guard 2: no other tracked file declares the outgoing version as
# `version = "X"` or `"version": "X"`, or it would go stale at this release.
guard_strays() {
  local current re file skip allowed stray=()
  current="$(jq -r .version "$pkg")"
  re="\"?version\"?[[:space:]]*[:=][[:space:]]*\"?${current//./\\.}\"?"
  git rev-parse --git-dir >/dev/null 2>&1 || return 0
  while IFS= read -r -d '' file; do
    skip=0
    for allowed in "${rewritten[@]}" "${exempt[@]}"; do [ "$file" = "$allowed" ] && skip=1; done
    [ "$skip" = 1 ] && continue
    ! grep -qIE "$re" "$file" 2>/dev/null || stray+=("$file")
  done < <(git ls-files -z)
  [ "${#stray[@]}" = 0 ] || { echo "these files declare the outgoing version $current but are not rewritten, so they would go stale:" >&2; printf '  %s\n' "${stray[@]}" >&2; exit 2; }
}

case "${1:-}" in
  --check)
    want="$(jq -r .version "$pkg")"
    bad=0
    for pair in "$conf:$(jq -r .version "$conf")" "$toml:$(toml_version)" "$lock:$(lock_version)"; do
      file="${pair%%:*}" got="${pair#*:}"
      [ -f "$file" ] || continue
      [ "$got" = "$want" ] || { echo "$file is $got; $pkg is $want" >&2; bad=1; }
    done
    exit "$bad"
    ;;
  [0-9]*.[0-9]*.[0-9]*)
    version="$1"
    [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || { echo "not a semantic version: $version" >&2; exit 2; }
    guard_forwards "$version"
    guard_strays
    for file in "$pkg" "$conf"; do
      jq --tab --arg v "$version" '.version = $v' "$file" > "$file.new" && mv "$file.new" "$file"
    done
    awk -v v="$version" '!done && /^version = "/ { $0 = "version = \"" v "\""; done = 1 } { print }' "$toml" > "$toml.new" && mv "$toml.new" "$toml"
    if [ -f "$lock" ]; then
      awk -v n="$name" -v v="$version" '
        $0 == "name = \"" n "\"" { print; getline; if ($1 == "version") $0 = "version = \"" v "\""; print; next }
        { print }' "$lock" > "$lock.new" && mv "$lock.new" "$lock"
    fi
    bash "$0" --check
    ;;
  *)
    echo "usage: $0 X.Y.Z | --check" >&2
    exit 2
    ;;
esac
